-- ============================================================================
-- CINEBOX (MOVIEBOX PRO) - GLOBAL SUPABASE SQL SCHEMA & RLS POLICIES
-- ============================================================================
-- Run this script in your Supabase SQL Editor to create all 3 global tables
-- (`movie_links`, `app_users`, `app_config`), indexes, and Row-Level Security
-- (RLS) policies for Read + Write (Upsert) across Web & Capacitor Android APK.
-- ============================================================================

-- 1. Create `movie_links` table for Hybrid Video Player & Bulk Movie Uploads
CREATE TABLE IF NOT EXISTS public.movie_links (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tmdb_id INTEGER NOT NULL UNIQUE,
  title TEXT NOT NULL DEFAULT '',
  language TEXT NOT NULL DEFAULT 'Hindi',
  direct_video_url TEXT DEFAULT NULL,
  stream_url TEXT DEFAULT NULL,
  download_480p TEXT DEFAULT NULL,
  download_720p TEXT DEFAULT NULL,
  download_1080p TEXT DEFAULT NULL,
  file_size_480p TEXT DEFAULT '450.0MB',
  file_size_720p TEXT DEFAULT '1020.6MB',
  file_size_1080p TEXT DEFAULT '2150.0MB',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_movie_links_tmdb_id ON public.movie_links (tmdb_id);

-- 2. Create `app_users` table for Global Users Control (Web + Capacitor APK)
CREATE TABLE IF NOT EXISTS public.app_users (
  id TEXT PRIMARY KEY,
  username TEXT NOT NULL,
  email TEXT NOT NULL,
  role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('user', 'vip', 'moderator', 'admin')),
  status TEXT NOT NULL DEFAULT 'active' CHECK (status IN ('active', 'suspended', 'banned')),
  platform TEXT NOT NULL DEFAULT 'Android APK',
  device_id TEXT DEFAULT '',
  vip_until TEXT DEFAULT '2027-12-30',
  downloads_count INTEGER NOT NULL DEFAULT 0,
  notes TEXT DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 3. Create `app_config` table for Global Decentralized Sync, Branding & SmartLink Ads
CREATE TABLE IF NOT EXISTS public.app_config (
  id INTEGER PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  app_name TEXT NOT NULL DEFAULT 'CineBox',
  primary_theme TEXT NOT NULL DEFAULT 'neon-green',
  is_ads_enabled BOOLEAN NOT NULL DEFAULT TRUE,
  popup_ad_image TEXT NOT NULL DEFAULT '',
  popup_ad_link TEXT NOT NULL DEFAULT 'https://movie-box.co/offer',
  direct_ad_link TEXT NOT NULL DEFAULT 'https://movie-box.co/smartlink',
  banner_ad_html TEXT NOT NULL DEFAULT '',
  admin_pin_hash TEXT NOT NULL DEFAULT '1234',
  admin_email TEXT NOT NULL DEFAULT 'ZulqarnainShah25@gmail.com',
  official_website TEXT NOT NULL DEFAULT 'https://movie-box.co',
  decentralized_manifest_url TEXT NOT NULL DEFAULT '',
  maintenance_mode BOOLEAN NOT NULL DEFAULT FALSE,
  allow_guest_downloads BOOLEAN NOT NULL DEFAULT TRUE,
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 4. Enable Row-Level Security (RLS) & Grant Read + Write (Upsert) Policies
ALTER TABLE public.movie_links ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.app_config ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Allow full access on movie_links" ON public.movie_links;
CREATE POLICY "Allow full access on movie_links"
  ON public.movie_links FOR ALL TO anon, authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow full access on app_users" ON public.app_users;
CREATE POLICY "Allow full access on app_users"
  ON public.app_users FOR ALL TO anon, authenticated
  USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Allow full access on app_config" ON public.app_config;
CREATE POLICY "Allow full access on app_config"
  ON public.app_config FOR ALL TO anon, authenticated
  USING (id = 1) WITH CHECK (id = 1);

GRANT ALL ON TABLE public.movie_links TO anon, authenticated;
GRANT ALL ON TABLE public.app_users TO anon, authenticated;
GRANT ALL ON TABLE public.app_config TO anon, authenticated;
